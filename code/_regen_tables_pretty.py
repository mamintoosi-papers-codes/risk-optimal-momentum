"""Regenerate tab_regression / tab_classification / tab_noise with canonical names."""
from pathlib import Path
import json
import sys

sys.path.insert(0, str(Path(__file__).resolve().parent))
from paper_tables import write_tex  # noqa: E402
from dataset_names import pretty  # noqa: E402

OUT = Path(__file__).resolve().parent.parent / "out"
PAPER = Path(__file__).resolve().parent.parent / "paper"

pt = json.loads((OUT / "paper_tables.json").read_text())
write_tex(pt["regression"], pt["classification"])
print("tab_regression / tab_classification rewritten")

rows = json.loads((OUT / "noise_sweep.json").read_text())["rows"]
lines = [
    "% Auto-generated by noise_sweep.py",
    r"\begin{tabular}{llccc}",
    r"\toprule",
    r"Problem & Noise & AdamW & SR-Adam & Gap \\",
    r"\midrule",
]
for r in rows:
    name = pretty(r["problem"])
    if r.get("metric") == "acc_frac":
        gap_pp = 100 * r["paired_diff"]
        gap_s = f"${gap_pp:+.1f}$pp"
        if gap_pp > 0:
            gap_s = r"$\bm{" + f"{gap_pp:+.1f}" + r"}$pp"
        lines.append(
            f"{name} & {r['noise']:.1f} & {100*r['adamw']:.1f} & "
            f"{100*r['sradam']:.1f} & {gap_s} \\\\"
        )
    else:
        gap = r["paired_diff"]
        gap_s = f"${gap:+.4f}$"
        if gap > 0:
            gap_s = r"$\bm{" + f"{gap:+.4f}" + r"}$"
        lines.append(
            f"{name} & {r['noise']:.1f} & {r['adamw']:.4f} & "
            f"{r['sradam']:.4f} & {gap_s} \\\\"
        )
lines += [r"\bottomrule", r"\end{tabular}"]
(PAPER / "tab_noise.tex").write_text("\n".join(lines) + "\n")
print("tab_noise rewritten")

for fn in ("tab_regression.tex", "tab_classification.tex", "tab_noise.tex"):
    print("---", fn, "---")
    print((PAPER / fn).read_text())
